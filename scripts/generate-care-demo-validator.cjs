/* eslint-disable @typescript-eslint/no-require-imports */
const { readFileSync, writeFileSync } = require("node:fs");
const { join } = require("node:path");
const Ajv2020 = require("ajv/dist/2020").default;
const addFormats = require("ajv-formats").default;
const standaloneCode = require("ajv/dist/standalone").default;
const schema = require("../schemas/care-demo-state.schema.json");

const ajv = new Ajv2020({ ownProperties: true, code: { source: true, lines: true } });
addFormats(ajv, ["date-time"]);
const source = "/* eslint-disable */\n// Generated by npm run generate:care-demo.\n"
  + standaloneCode(ajv, ajv.compile(schema));
const output = join(__dirname, "../lib/care-demo-validator.cjs");

if (process.argv.includes("--check")) {
  if (readFileSync(output, "utf8") !== source) {
    throw new Error("Care demo validator is out of date. Run npm run generate:care-demo.");
  }
} else {
  writeFileSync(output, source);
}
